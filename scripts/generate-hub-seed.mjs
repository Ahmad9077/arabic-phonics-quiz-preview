import fs from 'node:fs/promises'
import process from 'node:process'

const lettersUrl = new URL('../src/data/letters.json', import.meta.url)
const outputUrl = new URL('../integration/seed-arabic-phonics.sql', import.meta.url)
const letters = JSON.parse(await fs.readFile(lettersUrl, 'utf8'))
const familySizes = new Map()

for (const letter of letters) {
  familySizes.set(letter.family, (familySizes.get(letter.family) ?? 0) + 1)
}

function sqlText(value) {
  return `'${String(value).replaceAll("'", "''")}'`
}

function profileDifficulty(letter, mode) {
  const formBase = { isolated: 30, final: 50, initial: 64 }[mode]
  const familyPenalty = (familySizes.get(letter.family) ?? 1) > 1 ? 6 : 0
  return formBase + familyPenalty
}

const profiles = letters.flatMap((letter) => {
  const modes = letter.joining === 'dual'
    ? ['isolated', 'initial', 'final']
    : ['isolated', 'final']

  return modes.map((mode) => {
    const difficulty = profileDifficulty(letter, mode)
    const topicTags = [
      'arabic_phonics',
      `form_${mode}`,
      `family_${letter.family.replaceAll('-', '_')}`,
      `joining_${letter.joining}`,
    ]
    const skillTags = ['sound_to_symbol', mode === 'isolated' ? 'base_letter' : 'joining_form']
    return {
      questionKey: `${letter.id}:${mode}`,
      difficulty,
      topicTags,
      skillTags,
    }
  })
})

if (letters.length !== 28 || profiles.length !== 78) {
  throw new Error(`Expected 28 letters and 78 profiles; received ${letters.length} and ${profiles.length}.`)
}

const rows = profiles.map((profile) => {
  const topics = `array[${profile.topicTags.map(sqlText).join(', ')}]`
  const skills = `array[${profile.skillTags.map(sqlText).join(', ')}]`
  return `  ('arabic-phonics', ${sqlText(profile.questionKey)}, ${profile.difficulty}, ${topics}, ${skills})`
})

const sql = `-- Approved production seed for Arabic Phonics / صدى الحروف.
-- Generated by scripts/generate-hub-seed.mjs and approved for release on 2026-08-14.
-- Intentionally creates no quiz_assignments.

begin;

insert into public.quizzes (id, title, url, icon, color, sort_order)
values (
  'arabic-phonics',
  'صدى الحروف',
  'https://ahmad9077.github.io/arabic-phonics-quiz/',
  'أ',
  '#efe8ff',
  70
)
on conflict (id) do update set
  title = excluded.title,
  url = excluded.url,
  icon = excluded.icon,
  color = excluded.color,
  sort_order = excluded.sort_order;

insert into public.question_difficulty_profiles (
  quiz_id,
  question_key,
  difficulty,
  topic_tags,
  skill_tags
)
values
${rows.join(',\n')}
on conflict (quiz_id, question_key) do update set
  difficulty = excluded.difficulty,
  topic_tags = excluded.topic_tags,
  skill_tags = excluded.skill_tags,
  updated_at = now();

do $$
begin
  if (select count(*) from public.question_difficulty_profiles where quiz_id = 'arabic-phonics') <> 78 then
    raise exception 'Arabic Phonics profile count must be exactly 78';
  end if;
end
$$;

commit;

select
  quiz_id,
  count(*) as seeded_questions,
  min(difficulty) as min_difficulty,
  max(difficulty) as max_difficulty
from public.question_difficulty_profiles
where quiz_id = 'arabic-phonics'
group by quiz_id;
`

if (process.argv.includes('--check')) {
  const existing = await fs.readFile(outputUrl, 'utf8').catch(() => '')
  if (existing !== sql) {
    throw new Error('Approved Hub seed is stale. Run npm run generate:hub-seed.')
  }
  console.log(`Approved Hub seed is current with ${profiles.length} adaptive profiles.`)
} else {
  await fs.mkdir(new URL('../integration/', import.meta.url), { recursive: true })
  await fs.writeFile(outputUrl, sql)
  console.log(`Generated ${profiles.length} adaptive profiles at ${outputUrl.pathname}`)
}
